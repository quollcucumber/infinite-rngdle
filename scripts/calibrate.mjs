// Scores every possible roll (0..1,000,000) to derive badge EP values and the roll-rarity distribution.
import { writeFileSync } from 'node:fs';
import { BADGES, MAX, matchIds, applyCounts, analyze } from '../js/badges.js';

const counts = Object.fromEntries(BADGES.map((b) => [b.id, 0]));
for (let n = 0; n <= MAX; n++) for (const b of matchIds(n)) counts[b.id]++;
applyCounts(counts);

const hist = new Map();
for (let n = 0; n <= MAX; n++) {
  const { total } = analyze(n);
  hist.set(total, (hist.get(total) || 0) + 1);
}
const histogram = [...hist].sort((a, b) => a[0] - b[0]);

const out = `// Generated by scripts/calibrate.mjs — do not edit by hand.\nexport const BADGE_COUNTS = ${JSON.stringify(counts)};\nexport const EP_HISTOGRAM = ${JSON.stringify(histogram)};\n`;
writeFileSync(new URL('../js/calibration.js', import.meta.url), out);

for (const b of [...BADGES].sort((a, b) => b.count - a.count)) console.log(b.count.toString().padStart(7), b.ep.toString().padStart(4), b.rarity.padEnd(8), b.id);
console.log('distinct totals', histogram.length, 'max', histogram.at(-1));
